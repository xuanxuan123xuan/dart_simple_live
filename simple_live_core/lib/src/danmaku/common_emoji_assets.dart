/// 从弹幕文本提取 `[表情名]` token 转图文混排片段；
/// 命中 [commonEmojiAssets] 的转图片 span，未命中的方括号文本保持原样。
List<LiveMessageSpan> buildCommonEmojiSpans(String content) {
  final spans = <LiveMessageSpan>[];
  var start = 0;
  for (final match in _commonEmojiTokenPattern.allMatches(content)) {
    if (match.start > start) {
      spans.add(LiveMessageSpan.text(content.substring(start, match.start)));
    }
    final url = commonEmojiAssets[match.group(0)];
    if (url != null) {
      spans.add(LiveMessageSpan.image(url));
    } else {
      spans.add(LiveMessageSpan.text(match.group(0)!));
    }
    start = match.end;
  }
  if (start < content.length) {
    spans.add(LiveMessageSpan.text(content.substring(start)));
  }
  return spans;
}

