#!/usr/bin/env python3
"""Copy the Dart danmaku emoji tables into Swift sources."""

import argparse
import json
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parents[1]
DART = ROOT / "simple_live_core/lib/src/danmaku"
SWIFT = ROOT / "simple_live_tvos_native/Sources"
ENTRY = re.compile(r"""\s*(['"])([^'"\\\r\n]+)\1:\s*(['"])([^'"\\\r\n]+)\3,""")
TABLES = {
    "common": [("common", "commonEmojiAssets", "urls")],
    "douyu": [("douyu", "douyuEmojiAssets", "urls")],
    "huya": [("huya", "huyaEmojiAssets", "urls")],
    "kuaishou": [
        ("kuaishou", "kuaishouEmojiAssets", "web"),
        ("kuaishou_mobile", "kuaishouMobileEmojiAssets", "mobile"),
        ("kuaishou", "_kuaishouEmojiAliasMap", "aliases"),
    ],
}


def read_table(source, name):
    body = source.read_text(encoding="utf-8").split(
        f"const Map<String, String> {name} = {{\n", 1
    )[1].split("\n};", 1)[0]
    entries = {}
    position = 0
    while body[position:].strip():
        match = ENTRY.match(body, position)
        if match is None:
            raise ValueError(f"Unexpected Dart map entry in {source}: {body[position:position + 80]!r}")
        _, token, _, value = match.groups()
        entries[token] = value
        position = match.end()
    return entries


def generate(platform):
    enum = f"{platform.capitalize()}DanmakuEmojiAssets"
    lines = [
        "// Generated by tool/generate_tvos_danmaku_emoji.py.",
        f"enum {enum} {{",
    ]
    for source, dart_name, swift_name in TABLES[platform]:
        filename = f"{source}_emoji_assets.dart"
        lines.append(f"    // simple_live_core/lib/src/danmaku/{filename}")
        if source == "common":
            lines.append("    // Twemoji by Twitter and contributors, CC BY 4.0 (https://github.com/twitter/twemoji).")
        lines.append(f"    static let {swift_name}: [String: String] = [")
        for token, value in read_table(DART / filename, dart_name).items():
            key = json.dumps(token, ensure_ascii=False)
            url = json.dumps(value, ensure_ascii=False)
            lines.append(f"        {key}: {url},")
        lines.append("    ]")
    return SWIFT / f"{enum}.swift", "\n".join([*lines, "}", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for platform in TABLES:
        target, contents = generate(platform)
        if args.check:
            if not target.is_file() or target.read_text(encoding="utf-8") != contents:
                raise SystemExit(f"Regenerate {target.name} with {Path(__file__).name}")
        else:
            target.write_text(contents, encoding="utf-8")
